class Player:
    def __init__(self, id: int, first_name: str, last_name: str, nickname: str, victories: int, defeats: int, draws: int):
        self.id = id
        self.first_name = first_name
        self.last_name = last_name
        self.nickname = nickname
        self.victories = victories
        self.defeats = defeats
        self.draws = draws
